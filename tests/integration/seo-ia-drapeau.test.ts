import { eq } from 'drizzle-orm'
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest'
import { db } from '../../server/utils/db'
import { vitrines } from '../../shared/db/schema'
import { schemaOnboardingEtape, schemaOnboardingTerminer } from '../../shared/schemas/onboarding'
import { schemaVitrineUpdate } from '../../shared/schemas/vitrine'
import { IDENTITE_DEMO } from '../unit/support/ia-fixtures'
import { signatureAttendue } from '../unit/support/seo-ia'
import { createUser, insertMediaRow } from './support/fabriques'
import { definirModeFaux, iaFaux, reinitialiserIa } from './support/ia'
import { compterJobsFond, creerVitrineSeo, fermerFileFond, viderFileFond } from './support/seo-ia'

// Décision #24 : SEO_IA_REGENERATION_ACTIVE=false coupe la régénération en tâche de fond (frein d'urgence : coût IA,
// incident fournisseur) MAIS pas la génération à l'onboarding, qui fait partie de l'appel IA existant.
// `env` est lu une fois puis mis en cache : la variable est posée AVANT de réimporter les modules (resetModules),
// donc ce scénario vit dans son propre fichier. Les fabriques de test gardent la connexion d'origine (même base).

type Modules = {
  vitrines: typeof import('../../server/services/vitrines')
  onboarding: typeof import('../../server/services/onboarding')
  generations: typeof import('../../server/services/ia/generations')
}

let modules: Modules
const ancienne = process.env.SEO_IA_REGENERATION_ACTIVE

beforeAll(async () => {
  process.env.SEO_IA_REGENERATION_ACTIVE = 'false'
  vi.resetModules()
  modules = {
    vitrines: await import('../../server/services/vitrines'),
    onboarding: await import('../../server/services/onboarding'),
    generations: await import('../../server/services/ia/generations'),
  }
})

beforeEach(async () => {
  await reinitialiserIa()
  await viderFileFond()
})

afterAll(async () => {
  if (ancienne === undefined) delete process.env.SEO_IA_REGENERATION_ACTIVE
  else process.env.SEO_IA_REGENERATION_ACTIVE = ancienne
  // Rien à fermer : `db` et `redis` sont des singletons de globalThis, partagés avec le harnais (setup.ts les ferme).
  await fermerFileFond()
})

describe('SEO_IA_REGENERATION_ACTIVE=false', () => {
  it.each([
    ['métier', { metier: 'Pédiatre' }],
    ['ville', { ville: 'Yaoundé' }],
    ['accroche', { accroche: 'Une accroche toute neuve' }],
  ])('should plan NO job when the %s changes, but still save the change', async (_nom, changement) => {
    const { user, vitrine } = await creerVitrineSeo({ ia: 'frais' })

    await modules.vitrines.updateVitrine(user.id, schemaVitrineUpdate.parse(changement))

    expect(await compterJobsFond()).toBe(0)
    const [ligne] = await db.select().from(vitrines).where(eq(vitrines.id, vitrine.id))
    expect(ligne).toMatchObject(changement)
  })

  it('should plan NO job when a stale or missing proposal is published, and still publish', async () => {
    const { user, vitrine } = await creerVitrineSeo({ publiee: false, ia: 'perime' })

    await modules.vitrines.publishVitrine(user.id)

    expect(await compterJobsFond()).toBe(0)
    const [ligne] = await db.select().from(vitrines).where(eq(vitrines.id, vitrine.id))
    expect(ligne?.publieeLe).toBeInstanceOf(Date)
  })

  it('should STILL write the seo generated by the onboarding (the flag only stops the background regeneration)', async () => {
    const user = await createUser()
    const media = await insertMediaRow(user.id)
    await modules.onboarding.saveEtape(user.id, schemaOnboardingEtape.parse({ etape: 1, ...IDENTITE_DEMO }))
    await modules.onboarding.saveEtape(user.id, schemaOnboardingEtape.parse({ etape: 2, photoMediaId: media.id }))
    const { creerFauxProvider } = await iaFaux()
    await definirModeFaux('normal')
    const { generation } = await modules.onboarding.generer(user.id)
    await modules.generations.executeGeneration(generation.id, { provider: creerFauxProvider(), now: Date.now, sleep: async () => undefined })
    await modules.onboarding.saveEtape(user.id, schemaOnboardingEtape.parse({ etape: 3, accrocheIndex: 2, presentation: 'Texte du professionnel.', servicesActifs: [true, true, true] }))

    await modules.onboarding.terminer(user.id, schemaOnboardingTerminer.parse({ username: 'dr-cabrel-flag', palette: 'sauge' }))

    const [vitrine] = await db.select().from(vitrines).where(eq(vitrines.userId, user.id))
    expect(vitrine?.seoIaTitre ?? '').toContain('Douala')
    expect(vitrine?.seoIaDescription ?? '').toContain('Douala')
    expect(vitrine?.seoIaSignature).toBe(signatureAttendue({ metier: IDENTITE_DEMO.metier, ville: IDENTITE_DEMO.ville, pays: IDENTITE_DEMO.pays, accroche: vitrine?.accroche ?? null }))
    expect(await compterJobsFond()).toBe(0)
  })

  it('should plan NO job at the end of an onboarding that produced no seo either (fallback): the flag is a kill switch', async () => {
    const user = await createUser()
    const media = await insertMediaRow(user.id)
    await modules.onboarding.saveEtape(user.id, schemaOnboardingEtape.parse({ etape: 1, ...IDENTITE_DEMO }))
    await modules.onboarding.saveEtape(user.id, schemaOnboardingEtape.parse({ etape: 2, photoMediaId: media.id }))
    const { creerFauxProvider } = await iaFaux()
    await definirModeFaux('panne')
    const { generation } = await modules.onboarding.generer(user.id)
    await modules.generations.executeGeneration(generation.id, { provider: creerFauxProvider(), now: Date.now, sleep: async () => undefined })
    await modules.onboarding.saveEtape(user.id, schemaOnboardingEtape.parse({ etape: 3, accrocheIndex: 0, presentation: 'Texte du professionnel.', servicesActifs: [true, true, true] }))

    await modules.onboarding.terminer(user.id, schemaOnboardingTerminer.parse({ username: 'dr-cabrel-flag2', palette: 'sauge' }))

    expect(await compterJobsFond()).toBe(0)
    const [vitrine] = await db.select().from(vitrines).where(eq(vitrines.userId, user.id))
    expect(vitrine?.seoIaSignature).toBeNull()
  })
})
